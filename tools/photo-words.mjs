#!/usr/bin/env node
/* DCR Portal 2 — writes site/js/map/photo-words.js from the photo files contract's shared cases
   (tests/vectors/photo_files_cases.json: a byte copy of DCR Desktop 2's tools/pglite_check/photo_files_cases.json,
   docs/PHOTO-FILES-ONEDRIVE.md §10, cited OD). Every text the phone shows about the shoot files in OneDrive,
   completion and the Ready for marketing list is a word of the cases, filled in: no line is worded here. Only the
   groups Portal 2 shows are kept (the setup, health and most copy words are DCR Desktop's).

     node tools/photo-words.mjs            write the module
     node tools/photo-words.mjs --check    exit 1 when the module is not what the cases give, or the copy is not the
                                           cases version CASES_VERSION with the SHA-256 CASES_SHA256 (tests run the same)

   Development only (tools/ is not part of the site). */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

export const CASES = new URL("../tests/vectors/photo_files_cases.json", import.meta.url);
export const OUT = new URL("../site/js/map/photo-words.js", import.meta.url);
/** The version of the cases this repository copies (DCR Desktop 2 photo/p5o bc7fb88, the OneDrive review's round 10, OD
    §28: files.disk_full - a PC's disk full while it sends, a beat state of its own - and three files_line cases). */
export const CASES_VERSION = 31;
/** The SHA-256 of that copy, as DCR Desktop 2 records it beside the source (tools/pglite_check/photo_files_cases.sha256;
    the build plan §6: a check in each repository compares its copy with the record). */
export const CASES_SHA256 = "d74cd7421bec1221afec870995828f97b0004e7de4b760744d9d7ffbf6bb94b5";
// the groups Portal 2 shows, whole; `share` and `copy` only for the lines the phone has: the Access tab's account field
// and sharing line (OD §8.2, §8.4) and the removal question; the phone's own hand-in lines (OD §3.3: js/photo-send.js -
// the pick, a name taken, a file sent again, a different copy twice, a refused Replace, a cancel after files reached
// OneDrive, the names photo_upload_files refuses), cancel_keep (the Keep it of a reopen's question and of the phone's
// asks), the phone's asks before Cancel it and Hand in what's there (OD §3.3 step 8: cancel_ask_phone,
// hand_in_ask_phone) and this_shoot (queued's {shoot} when the status names none)
export const GROUPS = ["files", "files_buttons", "completion", "told", "help", "ready", "hint"];
export const PICK = {
  share: ["field_label", "field_tip", "shared", "to_give", "to_remove", "not_company", "no_domain", "remove_ask"],
  copy: ["skipped_same", "skipped_same_one", "renamed", "renamed_one", "big_phone", "keep_screen", "not_media", "not_media_one", "pick_limit",
    "name_taken_sent", "sent_again", "sent_again_one", "not_intact", "replace_unavailable", "cancelled_sent", "cancelled_sent_one",
    "empty_file", "bad_char", "trailing", "reserved_name", "reserved_prefix", "too_deep", "too_long", "money", "too_many_files",
    "cancel_keep", "cancel_ask_phone", "hand_in_ask_phone", "hand_in_ask_phone_one", "this_shoot"],
};

/** The SHA-256 of the copy's bytes. */
export function casesSha256(bytes) { return createHash("sha256").update(bytes).digest("hex"); }

/** The words Portal 2 keeps, in the cases' order (each group's `_about` left out: it is the contract's, not a screen's). */
export function pickWords(cases) {
  const w = cases.words;
  const out = {};
  for (const g of GROUPS) {
    out[g] = {};
    for (const [k, v] of Object.entries(w[g])) if (k !== "_about") out[g][k] = v;
  }
  for (const [g, keys] of Object.entries(PICK)) {
    out[g] = {};
    for (const k of keys) {
      if (typeof w[g][k] !== "string") throw new Error("the cases have no words." + g + "." + k);
      out[g][k] = w[g][k];
    }
  }
  return out;
}

/** The module's text (LF, one key per line, the words as JSON strings). */
export function moduleText(cases) {
  const words = pickWords(cases);
  const lines = [
    "/* GENERATED by tools/photo-words.mjs from tests/vectors/photo_files_cases.json (version " + cases.version + ") - do not edit.",
    "   The words of the photo files contract (DCR Desktop 2 docs/PHOTO-FILES-ONEDRIVE.md §10): every text the phone shows",
    "   about the shoot files in OneDrive, completion and the Ready for marketing list, filled in by map/photo-files.js (fill). */",
    "",
    "export const CASES_VERSION = " + JSON.stringify(cases.version) + ";",
    "",
    "export const WORDS = Object.freeze({",
  ];
  for (const [g, group] of Object.entries(words)) {
    lines.push("  " + g + ": Object.freeze({");
    for (const [k, v] of Object.entries(group)) lines.push("    " + k + ": " + JSON.stringify(v) + ",");
    lines.push("  }),");
  }
  lines.push("});", "");
  return lines.join("\n");
}

function main() {
  const raw = readFileSync(CASES);
  const cases = JSON.parse(raw.toString("utf8"));
  const text = moduleText(cases);
  if (process.argv.includes("--check")) {
    let have = "";
    try { have = readFileSync(OUT, "utf8"); } catch (e) { have = ""; }
    if (cases.version !== CASES_VERSION || casesSha256(raw) !== CASES_SHA256) {
      console.error("tests/vectors/photo_files_cases.json is not the cases version " + CASES_VERSION + " DCR Desktop 2 recorded (SHA-256 " +
        casesSha256(raw) + ", recorded " + CASES_SHA256 + "): copy it again");
      process.exit(1);
    }
    if (have !== text) { console.error("site/js/map/photo-words.js is not what the cases give: run node tools/photo-words.mjs"); process.exit(1); }
    console.log("photo-words.js matches the cases (version " + cases.version + ", SHA-256 " + CASES_SHA256.slice(0, 12) + "…)");
    return;
  }
  writeFileSync(OUT, text);
  console.log("wrote site/js/map/photo-words.js (cases version " + cases.version + ")");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
